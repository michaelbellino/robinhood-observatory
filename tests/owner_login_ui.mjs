import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const link={href:'/auth/login?next=%2Fworkbench'};
const location={pathname:'/workbench',hash:'#fixture-ticket',search:'?secret=not-forwarded'};
const events={};
const context=vm.createContext({location,document:{querySelectorAll:()=>[link]},window:{addEventListener:(name,fn)=>{events[name]=fn;}}});
vm.runInContext(readFileSync('observatory/static/auth-return.js','utf8'),context);
assert.equal(link.href,'/auth/login?next=%2Fworkbench%23fixture-ticket');
location.hash='#newer-ticket';events.hashchange();
assert.equal(link.href,'/auth/login?next=%2Fworkbench%23newer-ticket');
location.hash='#back-ticket';events.pageshow();
assert.equal(link.href,'/auth/login?next=%2Fworkbench%23back-ticket');
location.hash='#<script>';events.hashchange();
assert.equal(link.href,'/auth/login?next=%2Fworkbench');
location.pathname='/trades';location.hash='#research';events.pageshow();
assert.equal(link.href,'/auth/login?next=%2Ftrades%23research');
location.pathname='/auth/callback';events.pageshow();
assert.equal(link.href,'/auth/login?next=%2Ftrades%23research');
console.log('Owner login anchor, history restore, unsafe anchor and query omission checks passed.');
